"""Data models for agent responses and execution traces."""

from __future__ import annotations

import time
import uuid
from dataclasses import dataclass, field


def _new_step_id() -> str:
    """Return a fresh trace-step id, unique across agents and processes."""
    return uuid.uuid4().hex


def elapsed_ms_since(started: float) -> float:
    """Milliseconds since a :func:`time.monotonic` mark, for ``TraceStep.elapsed_ms``.

    Monotonic on purpose: these are durations, and a wall-clock adjustment
    mid-turn must not produce a negative one.
    """
    return (time.monotonic() - started) * 1000


@dataclass
class TraceStep:
    """Single step in an agent's execution trace.

    Steps form a tree via ``parent_id``: the orchestrator's root steps
    have ``parent_id = None``; specialist steps are re-parented under
    the orchestrator's ``a2a_call`` step that triggered them.

    Attributes:
        agent: Name of the agent that performed the action.
        action: Type of action (``routing``, ``a2a_call``, ``tool_call``,
            ``response``, ...).
        detail: Human-readable description of the action or result.
        timestamp: Unix timestamp of execution.
        step_id: Unique identifier of this step.
        parent_id: Identifier of the parent step in the trace tree, or
            ``None`` for roots.
        elapsed_ms: Optional duration of the step in milliseconds.
        tokens: Optional token count produced by the step.
        prompt_tokens: Optional size of the prompt the step sent to the model —
            what the step *consumed* of the context window, as opposed to what
            it generated.
    """

    agent: str
    action: str
    detail: str
    timestamp: float = field(default_factory=time.time)
    step_id: str = field(default_factory=_new_step_id)
    parent_id: str | None = None
    elapsed_ms: float | None = None
    tokens: int | None = None
    prompt_tokens: int | None = None


@dataclass
class InputRequired:
    """Marker: the agent cannot continue without something only the user has.

    A specialist yields this from its stream instead of finishing. The A2A
    executor then parks the task in ``input-required`` rather than completing
    it, so the task stays open and a later message on the same task id resumes
    it — which is what makes a question a *pending* question rather than just
    the last thing the agent happened to say.

    The full loop: the orchestrator surfaces this as an ``input_required``
    event; the frontend echoes ``{"agent", "task_id"}`` back as
    ``context["pending"]`` with the user's next message; the orchestrator then
    skips routing and resumes that task on that agent. One question is pending
    at a time (the last one wins), and a parked task nobody answers is
    canceled after ``settings.a2a_parked_task_ttl``.

    Attributes:
        question: What to ask, phrased for the user.
        task_id: The parked task. Set by the client when it reads the state off
            the wire; a later message on this id resumes the task instead of
            opening an unrelated new one.
    """

    question: str
    task_id: str | None = None


@dataclass
class AgentResponse:
    """Response produced by an agent, including the execution trace.

    Attributes:
        content: Text content of the response generated by the agent.
        agent_name: Name of the agent that produced the response.
        trace: List of execution steps for traceability and debugging.
    """

    content: str
    agent_name: str
    trace: list[TraceStep] = field(default_factory=list)
