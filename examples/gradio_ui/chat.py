"""Gradio chat adapter.

Renders the orchestrator's headless :meth:`run` event stream as Gradio chat
bubbles, and owns all the Gradio-specific event handlers. This keeps the core
(``erebots/agents``) free of any UI framework: the orchestrator yields neutral
``AgentEvent``s; this adapter is the only place that knows about Gradio.
"""

from __future__ import annotations

import base64
import mimetypes
import time
from pathlib import Path

import gradio as gr

from erebots.agents.models import TraceStep
from erebots.agents.orchestrator.think_parser import ThinkSplitter

_ACTION_TAG = {
    "routing": "route",
    "a2a_call": "a2a",
    "relay": "reply",
    "tool_call": "tool",
    "tool_result": "result",
    "tool_error": "tool failed",
    "response": "response",
    "context_retrieval": "ctx",
    "processing": "turn",
    "error": "error",
}


def _file_to_data_url(filepath: str) -> str | None:
    path = Path(filepath)
    if not path.exists():
        return None
    mime_type = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    encoded = base64.b64encode(path.read_bytes()).decode("utf-8")
    return f"data:{mime_type};base64,{encoded}"


def _latest_user_content(messages: list[dict]) -> str | list[dict] | None:
    for message in reversed(messages):
        if message.get("role") == "user" and isinstance(message.get("content"), (str, list)):
            return message["content"]
    return None


def _split_reasoning(text: str) -> tuple[str, str]:
    splitter = ThinkSplitter()
    think, visible = [], []
    for kind, piece in [*splitter.feed(text), *splitter.flush()]:
        (think if kind == "think" else visible).append(piece)
    return "".join(think).strip(), "".join(visible).strip()


def _format_trace_markdown(orchestrator_name: str, trace: list[TraceStep], final_agent: str) -> str:
    if final_agent == orchestrator_name:
        lines = [f"Final answer generated by `{orchestrator_name}`.", ""]
    else:
        lines = [
            f"Final answer generated by `{final_agent}`.",
            f"`{orchestrator_name}` only routed the request and displayed the specialist response.",
            "",
        ]
    by_parent: dict[str | None, list[TraceStep]] = {}
    for step in trace:
        by_parent.setdefault(step.parent_id, []).append(step)
    all_ids = {step.step_id for step in trace}

    def walk(parent_id: str | None, depth: int):
        for step in by_parent.get(parent_id, []):
            detail = step.detail.strip()
            if len(detail) > 180:
                detail = detail[:177] + "..."
            tag = f"[{_ACTION_TAG.get(step.action, step.action)}]"
            metrics = []
            if step.elapsed_ms is not None:
                metrics.append(f"{int(step.elapsed_ms)}ms")
            if step.prompt_tokens is not None:
                metrics.append(f"{step.prompt_tokens} ctx")
            if step.tokens is not None:
                metrics.append(f"{step.tokens} tok")
            suffix = f" · {' · '.join(metrics)}" if metrics else ""
            lines.append(f"{' ' * (4 * depth)}- {tag} `{step.agent}` · `{step.action}`: {detail}{suffix}")
            walk(step.step_id, depth + 1)

    walk(None, 0)
    for step in trace:
        if step.parent_id is not None and step.parent_id not in all_ids:
            lines.append(f"- [orphan] `{step.agent}` · `{step.action}`: {step.detail.strip()}")
    return "\n".join(lines).strip()


def _upsert_step(trace: list[TraceStep], step: TraceStep) -> None:
    """Add a step, or replace the one with the same id.

    A step is emitted when its work starts (so the trace shows progress) and
    again when it finishes, carrying ``elapsed_ms``. Appending both would show
    the same call twice.
    """
    for i, existing in enumerate(trace):
        if existing.step_id == step.step_id:
            trace[i] = step
            return
    trace.append(step)


def _meta_bubble(title: str, status: str = "done") -> dict:
    return {"role": "assistant", "content": "", "metadata": {"title": title, "status": status}}


class GradioChat:
    """Binds an orchestrator to Gradio chat events (the only Gradio-aware layer)."""

    def __init__(self, orchestrator):
        self.orch = orchestrator

    # --- the streaming chat handler (async; Gradio drives it on the app loop) ---

    async def chat(self, messages, session_context=None):
        content = _latest_user_content(messages)
        if content is None:
            return
        start = time.time()
        trace: list[TraceStep] = []
        history = self.orch.conversation.sanitize_history(messages)
        context = await self.orch.conversation.build_request_context(session_context, history[:-1])
        # The handle of a specialist's unanswered question survives between
        # turns in the per-browser session dict; consuming it marks this
        # message as the answer, so the server resumes instead of re-routing.
        if isinstance(session_context, dict) and session_context.get("pending"):
            context["pending"] = session_context.pop("pending")

        messages.append(_meta_bubble("Routing request...", "pending"))
        # Indices, not negative offsets: a fan-out turn appends a bubble per
        # contributing specialist, so the status bubble stops being messages[-1].
        pending_idx = len(messages) - 1
        yield messages

        visible = ""
        reasoning = ""
        final_agent = self.orch.name
        answer_idx: int | None = None
        side_idx: dict[str, int] = {}
        side_text: dict[str, str] = {}

        async for event in self.orch.run(content, context):
            if event.type == "routing":
                plan = event.data.get("plan") or []
                if plan:
                    named = ", ".join(f"`{name}`" for name in plan)
                    messages[pending_idx] = _meta_bubble(f"Routed to {named}")
                    messages.append(_meta_bubble(f"Waiting for {named}...", "pending"))
                    pending_idx = len(messages) - 1
                else:
                    messages[pending_idx] = _meta_bubble(
                        "No specialist match — orchestrator answering"
                    )
                yield messages
            elif event.type == "trace" and event.trace_step:
                _upsert_step(trace, event.trace_step)
            elif event.type == "reasoning":
                # A contributor's own reasoning stays out of the answer's.
                if event.channel != "side":
                    reasoning += event.text
            elif event.type == "token":
                if event.channel == "side":
                    idx = side_idx.get(event.agent)
                    if idx is None:
                        # Inserted above the status bubble so contributions read
                        # in order and the status line stays last.
                        messages.insert(
                            pending_idx, _meta_bubble(f"`{event.agent}` is answering...", "pending")
                        )
                        idx = side_idx[event.agent] = pending_idx
                        pending_idx += 1
                        side_text[event.agent] = ""
                    side_text[event.agent] += event.text
                    messages[idx]["content"] = side_text[event.agent]
                else:
                    if answer_idx is None:
                        messages[pending_idx] = _meta_bubble("Streaming response...", "pending")
                        messages.append({"role": "assistant", "content": ""})
                        answer_idx = len(messages) - 1
                    visible += event.text
                    messages[answer_idx]["content"] = visible
                yield messages
            elif event.type == "input_required":
                # Remember which agent is waiting (last one wins): the question
                # itself already streamed as the answer text.
                if isinstance(session_context, dict) and event.data.get("task_id"):
                    session_context["pending"] = {
                        "agent": event.agent,
                        "task_id": event.data["task_id"],
                    }
            elif event.type == "final":
                final_agent = event.agent
                if answer_idx is None:  # specialist answer arrives whole
                    reasoning, visible = _split_reasoning(event.text)
            elif event.type == "error":
                visible = event.text
                if event.trace_step:
                    _upsert_step(trace, event.trace_step)

        elapsed = time.time() - start
        # Settle each contributor's bubble into a collapsed audit trail of what
        # that specialist actually said before the answer was composed.
        for name, idx in side_idx.items():
            bubble = _meta_bubble(f"Contribution · `{name}`")
            bubble["content"] = side_text[name]
            messages[idx] = bubble
        # The answer bubble, when streamed, is always the last one: contributor
        # bubbles are filled before composition starts.
        response_bubble = messages.pop() if answer_idx is not None else None
        messages[pending_idx] = _meta_bubble(f"Response · {final_agent} · {elapsed:.1f}s")
        messages.append(_meta_bubble(f"Trace · generated by `{final_agent}`"))
        messages[-1]["content"] = _format_trace_markdown(self.orch.name, trace, final_agent)
        if reasoning:
            bubble = _meta_bubble(f"Reasoning · `{final_agent}`")
            bubble["content"] = reasoning
            messages.append(bubble)
        messages.append(response_bubble or {"role": "assistant", "content": visible})
        await self.orch.conversation.persist_history(session_context, messages)
        yield messages

    # --- input handling + lifecycle ---

    async def restore_history(self, session_context=None):
        """Seed the chatbot with this user's stored conversation, on page load.

        This frontend owns its transcript: every turn posts the chatbot's
        messages, and an edit, a retry and a clear all *replace* what is
        stored. That only holds if the chatbot starts out holding the whole
        conversation — otherwise a reload would begin from an empty box and the
        first turn would replace the user's history with just that turn.
        """
        messages = await self.orch.conversation.load_history(session_context)
        if not messages:
            return gr.update()
        return gr.update(value=messages, height="65vh")

    def submit(self, message, history, session_context=None):
        history = history or []
        if isinstance(message, dict):
            text = (message.get("text") or "").strip()
            files = message.get("files", [])
        else:
            text = (message or "").strip()
            files = []
        content: list[dict] = []
        if text:
            content.append({"type": "text", "text": text})
        for f in files:
            filepath = f if isinstance(f, str) else f.get("path", "")
            data_url = _file_to_data_url(filepath) if filepath else None
            if data_url:
                content.append({"type": "image_url", "image_url": {"url": data_url}})
        if len(content) == 1 and content[0]["type"] == "text":
            history.append({"role": "user", "content": text})
        elif content:
            history.append({"role": "user", "content": content})
        return self.disable_input(), history, gr.update(height="65vh")

    def disable_input(self):
        return gr.update(value="", stop_btn=True, submit_btn=False, interactive=False)

    def enable_input(self):
        return gr.update(value="", stop_btn=False, submit_btn=True, interactive=True)

    async def stopped(self, messages, session_context=None):
        """Settle the chat after the user stopped a turn.

        Gradio cancelled the turn's task (``cancels`` on the stop event), so
        :meth:`chat` never reached its epilogue: status bubbles are still
        spinning and nothing was persisted. Mark them stopped and keep what did
        arrive. Cancelling the client side does not reach a specialist that is
        mid-way: a tool it already called stays applied, and the bubble says so.
        """
        messages = list(messages or [])
        for bubble in messages:
            meta = bubble.get("metadata")
            if meta and meta.get("status") == "pending":
                meta["status"] = "done"
                meta["title"] = f"Stopped · {meta['title']}"
        messages.append(
            _meta_bubble("Stopped · a specialist already running may still complete its work")
        )
        await self.orch.conversation.persist_history(session_context, messages)
        return messages

    async def handle_edit(self, history, session_context, edit_data: gr.EditData):
        new_history = None
        if isinstance(edit_data.index, int):
            new_history = history[: edit_data.index + 1]
            new_history[-1]["content"] = edit_data.value
            await self.orch.conversation.persist_history(session_context, new_history)
        return self.disable_input(), new_history

    async def handle_retry(self, history, session_context, retry_data: gr.RetryData):
        new_history = None
        if isinstance(retry_data.index, int):
            new_history = history[: retry_data.index + 1]
            await self.orch.conversation.persist_history(session_context, new_history)
        return self.disable_input(), new_history

    async def handle_clear(self, session_context=None):
        await self.orch.conversation.persist_history(session_context, [])
        return gr.update(height=0)
